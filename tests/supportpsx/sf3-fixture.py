#!/usr/bin/env python3
# Writes tests/supportpsx/sf3-fixture.h: an SF3 bank with one instrument, its two
# zones playing two samples that share one Ogg Vorbis stream. Needs oggenc on the
# PATH. Run from the repository root:
#   python3 tests/supportpsx/sf3-fixture.py > tests/supportpsx/sf3-fixture.h

import math
import struct
import subprocess
import tempfile
import wave

RATE = 22050
PERIOD = 50  # 441 Hz
POINTS = 2000
LOOP_START = 1000
LOOP_END = 2000

pcm = [int(16384 * math.sin(2 * math.pi * i / PERIOD)) for i in range(POINTS)]

with tempfile.TemporaryDirectory() as tmp:
    wav = tmp + "/s.wav"
    ogg = tmp + "/s.ogg"
    with wave.open(wav, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(struct.pack("<%dh" % POINTS, *pcm))
    subprocess.run(["oggenc", "--quiet", "-q", "0", "--serial", "1", "-o", ogg, wav], check=True)
    with open(ogg, "rb") as f:
        vorbis = f.read()


def chunk(fourcc, data):
    pad = b"\0" if len(data) & 1 else b""
    return fourcc + struct.pack("<I", len(data)) + data + pad


def lst(kind, data):
    return chunk(b"LIST", kind + data)


def name(s):
    return s.encode().ljust(20, b"\0")


info = chunk(b"ifil", struct.pack("<HH", 3, 0))
info += chunk(b"isng", b"EMU8000\0")
info += chunk(b"INAM", b"sf3 fixture\0")

phdr = name("Sine") + struct.pack("<HHHIII", 0, 0, 0, 0, 0, 0)
phdr += name("EOP") + struct.pack("<HHHIII", 0, 0, 1, 0, 0, 0)
pbag = struct.pack("<HHHH", 0, 0, 1, 0)
pmod = b"\0" * 10
pgen = struct.pack("<HHHH", 41, 0, 0, 0)
inst = name("Sine") + struct.pack("<H", 0) + name("EOI") + struct.pack("<H", 2)
ibag = struct.pack("<HHHHHH", 0, 0, 3, 0, 6, 0)
imod = b"\0" * 10
igen = struct.pack("<HBBHHHH", 43, 0, 63, 54, 1, 53, 0)
igen += struct.pack("<HBBHHHH", 43, 64, 127, 54, 1, 53, 1)
igen += struct.pack("<HH", 0, 0)
# Ogg Vorbis sample: start/end are byte offsets into smpl, loop points are
# sample offsets from the start of the decoded sample. 0x11 = mono | Vorbis.
shdr = b""
for n in ("Sine", "Sine2"):
    shdr += name(n) + struct.pack("<IIIIIBbHH", 0, len(vorbis), LOOP_START, LOOP_END, RATE, 69, 0, 0, 0x11)
shdr += name("EOS") + b"\0" * 26

pdta = b"".join(
    chunk(k, v)
    for k, v in [
        (b"phdr", phdr),
        (b"pbag", pbag),
        (b"pmod", pmod),
        (b"pgen", pgen),
        (b"inst", inst),
        (b"ibag", ibag),
        (b"imod", imod),
        (b"igen", igen),
        (b"shdr", shdr),
    ]
)
body = b"sfbk" + lst(b"INFO", info) + lst(b"sdta", chunk(b"smpl", vorbis)) + lst(b"pdta", pdta)
sf3 = chunk(b"RIFF", body)

print("#pragma once")
print()
print("// Generated by tests/supportpsx/sf3-fixture.py: one %d-point %d Hz sine at %d Hz," % (POINTS, RATE // PERIOD, RATE))
print("// looping over [%d, %d), stored as Ogg Vorbis in an SF3 bank. Samples \"Sine\" (keys 0-63)" % (LOOP_START, LOOP_END))
print("// and \"Sine2\" (keys 64-127) both point at it.")
print()
print("#include <stdint.h>")
print()
print("namespace SF3Fixture {")
print()
print("static constexpr unsigned c_rate = %d;" % RATE)
print("static constexpr unsigned c_period = %d;" % PERIOD)
print("static constexpr unsigned c_points = %d;" % POINTS)
print("static constexpr unsigned c_loopStart = %d;" % LOOP_START)
print("static constexpr unsigned c_loopEnd = %d;" % LOOP_END)
print("static constexpr double c_amplitude = 16384.0;")
print()
print("static const uint8_t c_bank[] = {")
for i in range(0, len(sf3), 16):
    print("    " + " ".join("0x%02x," % b for b in sf3[i : i + 16]))
print("};")
print()
print("}  // namespace SF3Fixture")
