#!/usr/bin/env python3
# Generates src/core/gte-write-to-use.h from the RESULTS.md of nugget's tests/gte/write-to-use:
#
#   python3 tools/gte-write-to-use/generate.py path/to/nugget/tests/gte/write-to-use/RESULTS.md \
#       > src/core/gte-write-to-use.h
#
# The "min N" column of each (command, register) row becomes the number of instructions that must
# separate the write from the command for the command to see the new value. MVMVA is measured on
# four encodings only; its rows are folded into needs per role (vector component, matrix entry
# position, translation component), and the script fails if two encodings disagree on a role.

import re
import sys

DATA = ["VXY0", "VZ0", "VXY1", "VZ1", "VXY2", "VZ2", "RGBC", "OTZ", "IR0", "IR1", "IR2", "IR3", "SXY0", "SXY1",
        "SXY2", "SXYP", "SZ0", "SZ1", "SZ2", "SZ3", "RGB0", "RGB1", "RGB2", "RES1", "MAC0", "MAC1", "MAC2", "MAC3",
        "IRGB", "ORGB", "LZCS", "LZCR"]
CTRL = ["R11R12", "R13R21", "R22R23", "R31R32", "R33", "TRX", "TRY", "TRZ", "L11L12", "L13L21", "L22L23", "L31L32",
        "L33", "RBK", "GBK", "BBK", "LR1LR2", "LR3LG1", "LG2LG3", "LB1LB2", "LB3", "RFC", "GFC", "BFC", "OFX", "OFY",
        "H", "DQA", "DQB", "ZSF3", "ZSF4", "FLAG"]
FUNCT = {"RTPS": 0x01, "NCLIP": 0x06, "OP": 0x0c, "DPCS": 0x10, "INTPL": 0x11, "MVMVA": 0x12, "NCDS": 0x13,
         "CDP": 0x14, "NCDT": 0x16, "NCCS": 0x1b, "CC": 0x1c, "NCS": 0x1e, "NCT": 0x20, "SQR": 0x28, "DCPL": 0x29,
         "DPCT": 0x2a, "AVSZ3": 0x2d, "AVSZ4": 0x2e, "RTPT": 0x30, "GPF": 0x3d, "GPL": 0x3e, "NCCT": 0x3f}
# Register index (0-31 data, 32-63 control) by name.
INDEX = {n: i for i, n in enumerate(DATA)}
INDEX.update({n: 32 + i for i, n in enumerate(CTRL)})
# MVMVA operands: matrix base (control index), vector registers, translation base (control index).
MATRIX = {"RT": 0, "LL": 8, "LC": 16}
TRANSLATION = {"TR": 5, "BK": 13, "FC": 21, "NONE": None}
VECTOR = {"V0": ("VXY0", "VZ0"), "V1": ("VXY1", "VZ1"), "V2": ("VXY2", "VZ2")}


def mvmva_role(enc, reg):
    """Role of control/data register `reg` as an input of MVMVA encoding `enc`, or None."""
    mx, v, cv = enc[0], enc[1], enc[2]
    if reg >= 32 and MATRIX[mx] <= reg - 32 < MATRIX[mx] + 5:
        return ("matrix", reg - 32 - MATRIX[mx])
    t = TRANSLATION[cv]
    if t is not None and reg >= 32 and t <= reg - 32 < t + 3:
        return ("translation", reg - 32 - t)
    if v == "IR" and reg in (9, 10, 11):
        return ("vector", reg - 9)  # IR1, IR2, IR3: x, y, z
    if v in VECTOR:
        xy, z = VECTOR[v]
        if reg == INDEX[xy]:
            return ("vector", "xy")
        if reg == INDEX[z]:
            return ("vector", 2)
    return None


def main():
    text = open(sys.argv[1]).read()
    need = {}  # (command, reg) -> min N
    mvmva = {}  # role -> {encoding label: min N}
    for section in re.split(r"^## ", text, flags=re.M)[1:]:
        title = section.splitlines()[0].strip()
        rows = re.findall(r"^\| (\w+) \| (\d) \|", section, flags=re.M)
        if not rows:
            continue
        m = re.match(r"MVMVA\((\w+),(\w+),(\w+)(?:,lm\d)?\)$", title)
        for name, n in rows:
            reg = INDEX[name]
            n = int(n)
            if m:
                role = mvmva_role(m.groups(), reg)
                if role is None:
                    sys.exit(f"{title} {name}: not an input of this encoding")
                mvmva.setdefault(role, {})[title] = n
            else:
                need[(FUNCT[title], reg)] = n
    # VXYn packs the x and y components in one register, so it is one measured role; it must
    # agree with the larger of the IR1 (x) and IR2 (y) needs.
    roles = {}
    bad = []
    for role, by in sorted(mvmva.items(), key=str):
        values = set(by.values())
        if len(values) != 1:
            bad.append(f"{role}: {by}")
        roles[role] = max(values)
    if bad:
        sys.exit("MVMVA encodings disagree:\n  " + "\n  ".join(bad))
    for k, count in (("matrix", 5), ("translation", 3), ("vector", 3)):
        for i in range(count):
            if (k, i) not in roles:
                sys.exit(f"MVMVA role {k} {i} unmeasured")
    vec = {i: roles[("vector", i)] for i in range(3)}
    vxy = roles.get(("vector", "xy"))
    if vxy is not None and vxy != max(vec[0], vec[1]):
        sys.exit(f"MVMVA VXY {vxy} disagrees with IR1/IR2 {vec[0]}/{vec[1]}")
    print("// Generated by tools/gte-write-to-use/generate.py from nugget tests/gte/write-to-use/RESULTS.md.")
    print("// Do not edit by hand.")
    print("")
    print("#pragma once")
    print("")
    print("#include <stdint.h>")
    print("")
    print("namespace PCSX {")
    print("namespace GTEWriteToUse {")
    print("")
    print("// Instructions needed between a write to a GTE register (0-31 data, 32-63 control) and a")
    print("// command for the command to read the new value. Pairs not listed need none.")
    print("struct Need {")
    print("    uint8_t funct;")
    print("    uint8_t reg;")
    print("    uint8_t need;")
    print("};")
    print("static constexpr Need c_needs[] = {")
    for (funct, reg), n in sorted(need.items()):
        if n == 0:
            continue
        name = DATA[reg] if reg < 32 else CTRL[reg - 32]
        cmd = [k for k, v in FUNCT.items() if v == funct][0]
        print(f"    {{0x{funct:02x}, {reg}, {n}}},  // {cmd} {name}")
    print("};")
    print("")
    print("// MVMVA, by the role of the register in the encoding: vector component x, y, z (IR1-IR3,")
    print("// or VXYn for x and y together and VZn for z), matrix entry pair 0-4 (R11R12 .. R33 and the")
    print("// same positions of LLM and LCM), translation component x, y, z (TR, BK or FC).")
    print(f"static constexpr uint8_t c_mvmvaVector[3] = {{{vec[0]}, {vec[1]}, {vec[2]}}};")
    print("static constexpr uint8_t c_mvmvaMatrix[5] = {" + ", ".join(str(roles[("matrix", i)]) for i in range(5)) + "};")
    print("static constexpr uint8_t c_mvmvaTranslation[3] = {" +
          ", ".join(str(roles[("translation", i)]) for i in range(3)) + "};")
    print("")
    print("}  // namespace GTEWriteToUse")
    print("}  // namespace PCSX")
    sys.stderr.write("MVMVA roles:\n")
    for role, by in sorted(mvmva.items(), key=str):
        sys.stderr.write(f"  {role}: {by}\n")


main()
